#!/usr/bin/env node
/**
 * Fill quran_verses.translation from Tanzil.
 *
 *   node scripts/ingest-translation.mjs > /tmp/translation.sql
 *   cd workers && npx wrangler d1 execute languagebuilder --local --file=/tmp/translation.sql
 *
 * ── Why ─────────────────────────────────────────────────────────────────────
 *
 * The column has existed all along and was empty for all 6,236 verses, so the
 * Meaning lens could only offer the word-by-word gloss chain. A gloss chain is not
 * a translation: "All praises and thanks | (be) to Allah | the Lord | of the
 * universe" is a parsing aid, and reading it as prose is precisely the mistake that
 * made three glosses look wrong earlier in this project when they were fine in
 * sequence.
 *
 * Saheeh International via tanzil.net, which is the same project the pinned Uthmani
 * text comes from, and one of the five independent translations already used to
 * check the glosses — so its provenance is established rather than assumed.
 *
 * Pinned by SHA-256 and refused on mismatch, the same gate as ingest-quran.mjs and
 * ingest-morphology.mjs. A translation that silently changed under us would be
 * undetectable by eye across 6,236 rows.
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const CACHE = join(root, 'data');
const FILE = join(CACHE, 'en.sahih.txt');
const URL_ = 'https://tanzil.net/trans/en.sahih';
const log = (m) => process.stderr.write(m + '\n');

const EXPECTED_VERSES = 6236;
/**
 * Pinned on first successful ingest. Left null until then rather than inventing a
 * digest: a checksum you made up is worse than no checksum, because it looks
 * verified.
 */
const PINNED_SHA256 = 'a1778a1a56695d9b59ae910809ec46d9f4a55f05961de51cd56e6ebcf9040883';

await mkdir(CACHE, { recursive: true });
if (!existsSync(FILE)) {
  if (process.argv.includes('--offline')) {
    log(`--offline given but ${FILE} is missing`);
    process.exit(1);
  }
  log(`fetching ${URL_}`);
  const res = await fetch(URL_);
  if (!res.ok) {
    log(`fetch failed: ${res.status}`);
    process.exit(1);
  }
  await writeFile(FILE, await res.text());
}

const raw = await readFile(FILE, 'utf-8');
const sha = createHash('sha256').update(raw).digest('hex');
if (PINNED_SHA256 && sha !== PINNED_SHA256) {
  log(`REFUSING: expected SHA-256 ${PINNED_SHA256}, got ${sha}`);
  process.exit(2);
}
log(`source verified by checksum (${sha.slice(0, 12)}…)`);

// Format is "surah|ayah|text", with trailing licence notes after the verses.
const verses = [];
for (const line of raw.split('\n')) {
  const parts = line.split('|');
  if (parts.length < 3) continue;
  const surah = Number(parts[0]);
  const ayah = Number(parts[1]);
  if (!Number.isInteger(surah) || !Number.isInteger(ayah)) continue;
  if (surah < 1 || surah > 114 || ayah < 1) continue;
  const text = parts.slice(2).join('|').trim();
  if (text) verses.push({ surah, ayah, text });
}

log(`parsed ${verses.length} verses`);
if (verses.length !== EXPECTED_VERSES) {
  log(`REFUSING: expected ${EXPECTED_VERSES} verses, parsed ${verses.length}`);
  process.exit(2);
}

// Spot-check three known verses before emitting. A parser that silently produced
// off-by-one alignment would otherwise attach every translation to the wrong ayah,
// which is exactly the failure mode the gloss alignment check was built for.
const check = (s, a, needle) => {
  const v = verses.find((x) => x.surah === s && x.ayah === a);
  if (!v || !v.text.toLowerCase().includes(needle.toLowerCase())) {
    log(`REFUSING: ${s}:${a} does not contain "${needle}" — got ${v ? v.text.slice(0, 60) : 'nothing'}`);
    process.exit(2);
  }
  log(`  ${s}:${a} ✓ ${v.text.slice(0, 52)}`);
};
check(1, 1, 'In the name of Allah');
check(2, 255, 'Allah - there is no deity except Him');
check(112, 1, 'He is Allah');

const q = (v) => `'${String(v).replace(/'/g, "''")}'`;
const out = [
  '-- Generated by scripts/ingest-translation.mjs — do not edit by hand.',
  '-- Saheeh International via https://tanzil.net/trans/en.sahih (CC-BY)',
  `-- Source SHA-256: ${sha}`,
];
for (const v of verses) {
  out.push(
    `UPDATE quran_verses SET translation = ${q(v.text)} WHERE surah = ${v.surah} AND ayah = ${v.ayah};`
  );
}
process.stdout.write(out.join('\n') + '\n');
log(`emitted ${verses.length} updates`);
