#!/usr/bin/env node
/**
 * Generate the placement-test questions module from content/assessments/placement-test.json.
 *
 *   node scripts/gen-assessment.mjs
 *
 * Why generate rather than import: the JSON lives outside the Next project root
 * (src/app), so it cannot be imported directly, and these questions are static
 * content that does not vary per user — a table and an endpoint would be
 * machinery for nothing. Generating a checked-in module keeps the JSON as the
 * single source of truth with no runtime dependency.
 *
 * This replaces 7 questions hardcoded in AssessmentFlow.tsx, which had drifted
 * from the bank and carried their own copy of the الرحيم error.
 */

import { readFile, writeFile } from 'node:fs/promises';

const SRC = 'content/assessments/placement-test.json';
const OUT = 'src/app/components/assessment/questions.generated.ts';

const raw = JSON.parse(await readFile(SRC, 'utf-8'));

const modules = raw.modules.map((m) => ({
  id: m.id,
  title: m.title,
  description: m.description ?? '',
  durationMinutes: m.duration_minutes ?? null,
  questions: m.questions.map((q) => {
    const options = (q.options ?? []).map((o) =>
      typeof o === 'string' ? { text: o, correct: false } : o
    );
    const correct = options.find((o) => o.correct);
    if (!correct) throw new Error(`${q.id}: no option marked correct`);
    if (options.filter((o) => o.correct).length > 1) {
      throw new Error(`${q.id}: more than one option marked correct`);
    }
    return {
      id: q.id,
      instruction: q.instruction ?? '',
      display: q.display ?? null,
      options: options.map((o) => o.text),
      correctAnswer: correct.text,
    };
  }),
}));

const total = modules.reduce((n, m) => n + m.questions.length, 0);

const body = `// GENERATED by scripts/gen-assessment.mjs from ${SRC} — do not edit.
//
// ${total} questions across ${modules.length} modules. Regenerate after editing the JSON.

export interface AssessmentQuestion {
  id: string;
  instruction: string;
  /** Arabic text or glyph to show above the options, if any. */
  display: string | null;
  options: string[];
  correctAnswer: string;
}

export interface AssessmentModule {
  id: string;
  title: string;
  description: string;
  durationMinutes: number | null;
  questions: AssessmentQuestion[];
}

export const ASSESSMENT_MODULES: AssessmentModule[] = ${JSON.stringify(modules, null, 2)};

export const TOTAL_QUESTIONS = ${total};
`;

await writeFile(OUT, body, 'utf-8');
process.stderr.write(`wrote ${OUT}: ${modules.length} modules, ${total} questions\n`);
for (const m of modules) {
  process.stderr.write(`  ${m.id.padEnd(16)} ${m.questions.length} questions\n`);
}
