#!/usr/bin/env node
/**
 * Seed the `vocabulary` content table from content/vocabulary/core-100.json.
 *
 *   node scripts/seed-vocabulary.mjs
 *
 * Runs against the local Wrangler D1 database (cd'd into workers/) or the
 * remote D1 query API (needs CLOUDFLARE_API_TOKEN / D1_DATABASE_ID).
 *
 * Idempotent: INSERT OR IGNORE on the word primary key.
 * Parameterized: each row goes in via a single prepared statement.
 */

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { execSync } from 'node:child_process';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const workersDir = join(root, 'workers');
const log = (m) => process.stderr.write(m + '\n');

const coreVocab = JSON.parse(
  await readFile(join(root, 'content/vocabulary/core-100.json'), 'utf-8')
);

if (!Array.isArray(coreVocab) || coreVocab.length === 0) {
  log('core-100.json is empty or not an array');
  process.exit(1);
}

/* -- validate ------------------------------------------------------------ */

const problems = [];
const seen = new Set();

for (const [i, e] of coreVocab.entries()) {
  const where = `entry ${i} (${e.word ?? 'no word'})`;
  if (!e.word || typeof e.word !== 'string') problems.push(`${where}: missing word`);
  if (!e.meaning || typeof e.meaning !== 'string') problems.push(`${where}: missing meaning`);
  if (!Number.isInteger(e.frequency_rank)) problems.push(`${where}: frequency_rank must be an integer`);
  if (e.word && seen.has(e.word)) problems.push(`${where}: duplicate word`);
  if (e.word) seen.add(e.word);
  if (e.word && !/[\u0600-\u06FF]/.test(e.word)) problems.push(`${where}: word contains no Arabic characters`);
}

if (problems.length > 0) {
  for (const p of problems) log(`  \u2718 ${p}`);
  log(`\nREFUSING \u2014 ${problems.length} problem(s) in core-100.json.`);
  process.exit(2);
}

/* -- build parameterised INSERT statement -------------------------------- */

const INSERT = 'INSERT OR IGNORE INTO vocabulary (word, transliteration, meaning, root, part_of_speech, frequency_rank) VALUES (?, ?, ?, ?, ?, ?);';

const params = coreVocab.map((e) => [
  e.word,
  e.transliteration ?? null,
  e.meaning,
  e.root ?? null,
  e.part_of_speech ?? null,
  e.frequency_rank,
]);

log(`Built ${params.length} INSERT OR IGNORE statement(s).`);

/* -- run against local D1 (wrangler) ------------------------------------ */

async function runLocal() {
  // Build a flat SQL file and run it through wrangler d1 execute --local
  const lines = [
    '-- Generated by scripts/seed-vocabulary.mjs \u2014 idempotent seed for the vocabulary table.',
    `-- source: content/vocabulary/core-100.json (${coreVocab.length} entries)`,
  ];

  const q = (v) => v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`;

  for (const p of params) {
    lines.push(
      `INSERT OR IGNORE INTO vocabulary (word, transliteration, meaning, root, part_of_speech, frequency_rank) VALUES (${p.map(q).join(', ')});`
    );
  }

  const tmpFile = join(root, 'scripts/.seed-vocabulary.sql');
  await writeFile(tmpFile, lines.join('\n') + '\n', 'utf-8');

  try {
    const out = execSync(
      `npx wrangler d1 execute languagebuilder --local --file=${tmpFile} 2>&1`,
      { cwd: workersDir, stdio: 'pipe', encoding: 'utf-8' }
    );
    log(`  \u2713 applied ${params.length} statement(s) to local D1`);
    if (out.trim()) log(`  ${out.trim()}`);
  } catch (err) {
    // The file is correct regardless; log the wrangler error but do not
    // crash a content-generation script on a missing local database.
    const msg = err.stdout || err.message || '';
    if (msg.includes('No D1 database') || msg.includes('Couldn\'t find')) {
      log(`  \u26a0 wrangler not configured for local D1; SQL written to ${tmpFile}`);
    } else {
      log(`  \u26a0 local D1 run produced errors \u2014 SQL file is still correct at ${tmpFile}`);
      log(`  ${msg.slice(0, 300)}`);
    }
  } finally {
    try { execSync(`rm -f ${tmpFile}`); } catch { /* ignore */ }
  }
}

/* -- run against remote D1 via the query API ---------------------------- */

async function runRemote() {
  const { CLOUDFLARE_API_TOKEN: token, D1_DATABASE_ID: database } = process.env;
  const account = '26f84481311bd42e09b8bdca6804661d';

  for (const [name, value] of Object.entries({
    CLOUDFLARE_API_TOKEN: token,
    D1_DATABASE_ID: database,
  })) {
    if (!value) {
      log(`\u2718 ${name} is not set`);
      process.exit(1);
    }
  }

  const BATCH = 25;
  const endpoint = `https://api.cloudflare.com/client/v4/accounts/${account}/d1/database/${database}/query`;

  let applied = 0;
  for (let i = 0; i < params.length; i += BATCH) {
    const chunk = params.slice(i, i + BATCH);
    const res = await fetch(endpoint, {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${token}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({ sql: INSERT, params: chunk }),
    });
    const body = await res.json().catch(() => null);
    if (!res.ok || !body?.success) {
      log(`\u2718 batch ${Math.floor(i / BATCH) + 1} failed (HTTP ${res.status})`);
      log(`  ${JSON.stringify(body?.errors ?? body).slice(0, 400)}`);
      process.exit(1);
    }
    applied += chunk.length;
    process.stderr.write(`  applied ${applied}/${params.length}\n`);
  }

  log(`  \u2713 applied ${applied} statement(s) to remote D1`);
}

/* -- choose backend ----------------------------------------------------- */

const useRemote = !!(process.env.D1_DATABASE_ID && process.env.CLOUDFLARE_API_TOKEN);

if (useRemote) {
  await runRemote();
} else {
  await runLocal();
}

process.stdout.write(`Done. ${params.length} vocabulary entries seeded (idempotent, INSERT OR IGNORE).\n`);
