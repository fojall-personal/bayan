#!/usr/bin/env node
/**
 * Emit seed SQL for the `vocabulary` content table from
 * content/vocabulary/core-100.json.
 *
 *   node scripts/gen-vocabulary.mjs > /tmp/vocabulary.sql
 *   cd workers && npx wrangler d1 execute languagebuilder --local  --file=/tmp/vocabulary.sql
 *   cd workers && npx wrangler d1 execute languagebuilder --remote --file=/tmp/vocabulary.sql
 *
 * Follows the same shape as scripts/gen-assessment.mjs: the JSON is the source of
 * truth, the SQL is generated, and nothing is hand-edited.
 *
 * Validates before emitting rather than letting a bad row reach the database,
 * because the failure mode here is quiet — a missing meaning renders as a blank
 * flashcard rather than an error.
 */

import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const log = (m) => process.stderr.write(m + '\n');

const q = (v) =>
  v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`;

const entries = JSON.parse(
  await readFile(join(root, 'content/vocabulary/core-100.json'), 'utf-8')
);

if (!Array.isArray(entries) || entries.length === 0) {
  log('core-100.json is empty or not an array');
  process.exit(1);
}

const problems = [];
const seen = new Set();

entries.forEach((e, i) => {
  const where = `entry ${i} (${e.word ?? 'no word'})`;
  if (!e.word || typeof e.word !== 'string') problems.push(`${where}: missing word`);
  if (!e.meaning || typeof e.meaning !== 'string') problems.push(`${where}: missing meaning`);
  if (!Number.isInteger(e.frequency_rank)) {
    problems.push(`${where}: frequency_rank must be an integer`);
  }
  if (e.word && seen.has(e.word)) problems.push(`${where}: duplicate word`);
  if (e.word) seen.add(e.word);
  // Arabic script check. A Latin-only "Arabic" word means the columns were
  // swapped somewhere upstream, which is easy to miss by eye.
  if (e.word && !/[؀-ۿ]/.test(e.word)) {
    problems.push(`${where}: word contains no Arabic characters`);
  }
});

if (problems.length) {
  for (const p of problems) log(`  ✘ ${p}`);
  log(`\nREFUSING TO EMIT — ${problems.length} problem(s) in core-100.json.`);
  process.exit(2);
}

const out = [
  '-- Generated by scripts/gen-vocabulary.mjs — do not edit by hand.',
  `-- source: content/vocabulary/core-100.json (${entries.length} entries)`,
  'DELETE FROM vocabulary;',
];

for (const e of entries) {
  out.push(
    'INSERT INTO vocabulary (word, transliteration, meaning, root, part_of_speech, frequency_rank) VALUES (' +
      [
        q(e.word),
        q(e.transliteration ?? null),
        q(e.meaning),
        q(e.root ?? null),
        q(e.part_of_speech ?? null),
        e.frequency_rank,
      ].join(', ') +
      ');'
  );
}

process.stdout.write(out.join('\n') + '\n');
log(`emitted ${entries.length} vocabulary rows`);
