#!/usr/bin/env node
/**
 * Generate TypeScript row types from the actual database schema.
 *
 *   node scripts/gen-db-types.mjs           # write workers/src/db/schema.ts
 *   node scripts/gen-db-types.mjs --check   # fail if it is out of date
 *
 * ── Why ─────────────────────────────────────────────────────────────────────
 *
 * Twenty-four handlers typed their rows as `Record<string, unknown>`. That is not
 * a type so much as an opt-out: `row.surah_id` and `row.surahid` both compile, both
 * are `unknown`, and every use needs a cast. It is the direct reason four column
 * names in quran.ts were wrong — the code said `surah_id` where the column is
 * `surah`, and nothing between the query and the response objected.
 *
 * Hand-written interfaces would fix the property checking and leave the real problem
 * in place: an interface is a second copy of the schema, and a copy can disagree with
 * the database. So these are derived from the schema itself.
 *
 * ── How ─────────────────────────────────────────────────────────────────────
 *
 * The migrations are applied to an in-memory SQLite database and the result is read
 * back with pragma_table_info. That matters because several migrations rebuild a
 * table via the create-copy-drop-rename dance, leaving `*_new` names in the SQL text
 * that do not exist afterwards, and fourteen ALTER TABLE ADD COLUMN statements add
 * columns the original CREATE never mentioned. Parsing the SQL would have to
 * reimplement all of that; running it does not.
 *
 * The generated file is committed and gated, so a migration that renames a column
 * turns every handler still using the old name into a compile error.
 */

import { DatabaseSync } from 'node:sqlite';
import { readFile, writeFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const MIGRATIONS = join(root, 'workers/src/db/migrations');
const OUT = join(root, 'workers/src/db/schema.ts');

const db = new DatabaseSync(':memory:');
const files = (await readdir(MIGRATIONS)).filter((f) => f.endsWith('.sql')).sort();
for (const f of files) {
  db.exec(await readFile(join(MIGRATIONS, f), 'utf-8'));
}

const tables = db
  .prepare(
    `SELECT name FROM sqlite_master
      WHERE type = 'table' AND name NOT LIKE 'sqlite_%'
      ORDER BY name`
  )
  .all()
  .map((r) => r.name);

/** SQLite's declared types, as they appear in these migrations. */
function tsType(declared) {
  const t = declared.toUpperCase();
  if (t.includes('INT')) return 'number';
  if (t.includes('REAL') || t.includes('FLOA') || t.includes('DOUB')) return 'number';
  if (t.includes('BLOB')) return 'ArrayBuffer';
  // TEXT, DATETIME, and an absent declaration all arrive as strings over D1.
  return 'string';
}

/** memorization_units → MemorizationUnitsRow */
const rowName = (table) =>
  table
    .split('_')
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join('') + 'Row';

const parts = [
  '// GENERATED by scripts/gen-db-types.mjs — do not edit.',
  '//',
  '// Row types read from the real schema: every migration applied to an in-memory',
  '// SQLite database, then pragma_table_info. Regenerate with:',
  '//',
  '//   node scripts/gen-db-types.mjs',
  '//',
  '// `npm run check:db-types` fails when this drifts, so a renamed column becomes a',
  '// compile error in every handler still selecting the old name — which is exactly',
  '// what `Record<string, unknown>` rows could not do.',
  '//',
  '// A nullable column is `| null` because that is what D1 returns. Use Pick<> to',
  '// describe a projection: a SELECT of three columns is not the whole row, and',
  '// saying so keeps the type honest.',
  '',
];

for (const table of tables) {
  const cols = db
    .prepare(`SELECT name, type, "notnull", pk FROM pragma_table_info(?)`)
    .all(table);
  parts.push(`export interface ${rowName(table)} {`);
  for (const c of cols) {
    const base = tsType(c.type ?? '');
    // SQLite reports notnull = 0 for a PRIMARY KEY column unless NOT NULL is spelled
    // out, but a primary key cannot be null — so `pk` counts as non-null too.
    // Otherwise every `id` would be typed `string | null` and every use would need a
    // guard that can never fire.
    const nullable = !c.notnull && !c.pk;
    parts.push(`  ${c.name}: ${nullable ? `${base} | null` : base};`);
  }
  parts.push('}', '');
}

const generated = parts.join('\n');
db.close();

let current = '';
try {
  current = await readFile(OUT, 'utf-8');
} catch {
  // First run.
}

if (check) {
  if (current !== generated) {
    process.stderr.write(
      '✘ workers/src/db/schema.ts is out of date with the migrations.\n' +
        '  Run: node scripts/gen-db-types.mjs\n'
    );
    process.exit(1);
  }
  process.stdout.write(
    `✅ schema.ts matches the migrations (${tables.length} tables from ${files.length} migrations)\n`
  );
  process.exit(0);
}

await writeFile(OUT, generated, 'utf-8');
process.stdout.write(
  `wrote ${tables.length} row types to workers/src/db/schema.ts from ${files.length} migrations\n`
);
